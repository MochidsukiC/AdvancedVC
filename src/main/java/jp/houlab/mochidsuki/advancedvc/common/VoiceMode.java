package jp.houlab.mochidsuki.advancedvc.common;

/**
 * 音声通信モード
 */
public enum VoiceMode {
    /**
     * シミュレーションモード（デフォルト）
     * - 物理法則ベースの音響シミュレーション
     * - VADで自動起動
     * - デバイスモードと同時使用可能
     */
    SIMULATION,

    /**
     * バンドモード（低遅延）
     * - リアルタイム音楽セッション用
     * - 全ての音響シミュレーション停止
     * - 目標遅延: 25-40ms
     * - 他モード一時停止
     */
    BAND,

    /**
     * デバイス通信モード（ウォーキートーキー）
     * - 距離無制限のグループチャット
     * - PTT（プッシュトゥートーク）
     * - 音響シミュレーション対象外
     * - シミュレーションモードと同時使用可能
     */
    DEVICE
}
